create temporary table assets_to_remove (asset_id integer primary key) on commit drop;
insert into assets_to_remove (asset_id)
select asset_id from assets
where market = 'india'
  and asset_type = 'equity'
  and ticker not in (select ticker from nifty500_keep);

-- Sanity check: how many stocks are about to be removed vs kept.
-- Expect "to_remove" to be roughly (current India equity count - ~500)
-- and "to_keep" to be close to 500 -- if these numbers look wrong,
-- stop here (don't run the rest of the file) and flag it instead of
-- proceeding.
select
  (select count(*) from assets_to_remove) as to_remove,
  (select count(*) from assets where market = 'india' and asset_type = 'equity') - (select count(*) from assets_to_remove) as to_keep;

-- Step 2: for every table with a foreign key pointing at
-- assets(asset_id) -- discovered from Postgres's own catalogs, not a
-- hand-typed list -- delete any row belonging to a stock we're
-- removing. Handles `peers.asset_id` AND `peers.peer_asset_id`
-- separately since both are real FKs to assets(asset_id).
do $$
declare
  r record;
  n bigint;
begin
  for r in
    select
      tc.table_schema,
      tc.table_name,
      kcu.column_name,
      tc.constraint_name
    from information_schema.table_constraints tc
    join information_schema.key_column_usage kcu
      on tc.constraint_name = kcu.constraint_name and tc.table_schema = kcu.table_schema
    join information_schema.constraint_column_usage ccu
      on tc.constraint_name = ccu.constraint_name and tc.table_schema = ccu.table_schema
    where tc.constraint_type = 'FOREIGN KEY'
      and ccu.table_schema = 'public'
      and ccu.table_name = 'assets'
      and ccu.column_name = 'asset_id'
      and tc.table_name <> 'assets'
  loop
    execute format(
      'delete from %I.%I where %I in (select asset_id from assets_to_remove)',
      r.table_schema, r.table_name, r.column_name
    );
    get diagnostics n = row_count;
    raise notice 'Cleared % row(s) from %.% (column %, constraint %)', n, r.table_schema, r.table_name, r.column_name, r.constraint_name;
  end loop;
end $$;

-- Step 3: finally remove the assets themselves.
delete from assets where asset_id in (select asset_id from assets_to_remove);

-- Final report -- should read 500 for India equities.
select count(*) as remaining_india_equities from assets where market = 'india' and asset_type = 'equity';

commit;
