-- 131_narrow_india_universe_to_nifty500.sql
-------------------------------------------------------------------
-- Avdhoot (P6, 2026-09-24): "Decrease the scope of Indian Stocks to
-- only NIFTY 500; lets not have all the 2500 stocks (remove the extra
-- above 500). This will free up supabase space, focus more on core
-- stocks, and also help us build this MVP very well."
--
-- Hard-deletes every India equity NOT in the current Nifty 500 index
-- (Avdhoot's explicit choice over soft-deactivating them -- this
-- actually frees up space, at the cost of being irreversible). The
-- keep-list below is this project's own `nifty500_master.csv` (already
-- in this repo, verified against NSE's own ind_nifty500list.csv --
-- more reliable than a fresh web fetch, which had one stale/renamed
-- symbol at the time this migration was written: HEGAM vs the
-- correct HEG, and a spurious DUMMYHEG placeholder row),
-- matched against `assets.ticker` for market='india', asset_type='equity'
-- (assets.ticker stores the bare NSE symbol, e.g. 'RELIANCE' -- same
-- convention 104_weekly_universe_sync_india.py already relies on).
--
-- IMPORTANT -- READ BEFORE RUNNING:
--   1. This is IRREVERSIBLE. It deletes price history, fundamentals,
--      scores, and every other row tied to the removed stocks, from
--      EVERY table that references assets(asset_id) -- discovered
--      automatically via Postgres's own foreign-key catalog (step 2
--      below), so this doesn't rely on a hand-maintained table list
--      that could miss one added by a later migration.
--   2. Take a backup first if you're not fully sure (Supabase Project
--      Settings -> Database -> Backups, or just export the `assets`
--      table) -- there is no undo once this commits.
--   3. This whole script runs inside one transaction (BEGIN/COMMIT at
--      the very top/bottom) -- if anything looks wrong from the
--      NOTICE lines Supabase prints while it runs, you can stop
--      before the COMMIT line and it rolls back cleanly. If you paste
--      the whole file at once into Supabase's SQL Editor, it commits
--      automatically at the end, same as any other migration in this
--      project -- reread the NOTICE output afterwards instead.
--   4. Two tables are NOT foreign-key-enforced and are deliberately
--      left untouched: `saved_comparisons.asset_ids` (a plain integer
--      array behind old share links) and any JSON blob elsewhere that
--      might mention a removed asset_id. Worst case, an old shared
--      comparison link for a removed stock stops resolving -- not a
--      data-integrity problem, just a dead link.
--   5. After this runs, ALSO update 104_weekly_universe_sync_india.py
--      (done in this same session, see BUILD_LOG) so future weekly
--      syncs keep sourcing from the Nifty 500 list, not NSE's full
--      ~2500-stock mainboard list -- otherwise the next weekly sync
--      would just re-add everything this script removes.
--
-- Safe to re-run: if the extra stocks are already gone, step 2/3
-- simply delete 0 rows.
-------------------------------------------------------------------

